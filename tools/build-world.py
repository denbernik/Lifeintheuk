"""Generate js/data/world.js: simplified country outlines for a world map and a Europe map.

Usage: python3 tools/build-world.py ne_50m_admin_0_map_units.geojson > js/data/world.js
Source: Natural Earth 1:50m admin-0 map units (public domain). Countries are keyed by ADM0_A3.
"""
import json, math, sys

VIEWS = {
    # name: (lon_min, lon_max, lat_min, lat_max, px_per_degree_lat, lat_for_x_scale, min_ring_area_px2)
    'world': (-169, 191, -56, 83, 2.2, 0, 2.0),
    'europe': (-11.5, 35, 34, 71.5, 13, 52, 4.0),
}
TOLERANCE = {'world': 0.55, 'europe': 0.6}


def simplify(pts, tol):
    """Douglas-Peucker on a closed ring (keeps the first point)."""
    if len(pts) < 5:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1e-9
        best, idx = -1, -1
        for i in range(a + 1, b):
            x0, y0 = pts[i]
            d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / L if (dx or dy) else math.hypot(x0 - x1, y0 - y1)
            if d > best:
                best, idx = d, i
        if best > tol:
            keep[idx] = True
            stack.append((a, idx)); stack.append((idx, b))
    return [p for p, k in zip(pts, keep) if k]


def ring_area(pts):
    a = 0
    for i in range(len(pts)):
        x1, y1 = pts[i]; x2, y2 = pts[(i + 1) % len(pts)]
        a += x1 * y2 - x2 * y1
    return abs(a) / 2


def build(features, view):
    lo0, lo1, la0, la1, s, latk, min_area = VIEWS[view]
    k = math.cos(math.radians(latk)) if latk else 1
    w = (lo1 - lo0) * k * s
    h = (la1 - la0) * s
    out = {}
    for f in features:
        code = f['properties'].get('ADM0_A3')
        g = f['geometry']
        if not g:
            continue
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        parts = []
        for poly in polys:
            ring = poly[0]
            pts, last = [], None
            for lon, lat in ring:
                if view == 'world' and lon < -169:
                    lon += 360
                x = round((lon - lo0) * k * s, 1)
                y = round((la1 - lat) * s, 1)
                if (x, y) != last:
                    pts.append((x, y)); last = (x, y)
            if len(pts) < 3 or ring_area(pts) < min_area:
                continue
            pts = simplify(pts + [pts[0]], TOLERANCE[view])[:-1]
            if len(pts) < 3:
                continue
            xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
            if max(xs) < -5 or min(xs) > w + 5 or max(ys) < -5 or min(ys) > h + 5:
                continue
            parts.append('M' + 'L'.join(f'{round(x):d},{round(y):d}' if view == 'world' else f'{x:g},{y:g}' for x, y in pts) + 'Z')
        if parts:
            out[code] = out.get(code, '') + ''.join(parts)
    return {'w': round(w), 'h': round(h), 'proj': {'lonMin': lo0, 'latMax': la1, 'k': round(k, 6), 'scale': s}, 'paths': out}


def main(path):
    feats = json.load(open(path))['features']
    data = {v: build(feats, v) for v in VIEWS}
    print('/* Generated by tools/build-world.py from Natural Earth 1:50m map units (public domain). */')
    print('window.WORLD_MAP = ' + json.dumps(data, separators=(',', ':')) + ';')


if __name__ == '__main__':
    main(sys.argv[1])

"""Generate js/data/map.js (SVG paths for the UK & Ireland) from a Natural Earth
admin-0 map-units GeoJSON file.

Usage: python3 tools/build-map.py ne_50m_admin_0_map_units.geojson > js/data/map.js
Source: https://github.com/nvkelso/natural-earth-vector (public domain)
"""
import json, math, sys

UNITS = {
    'England': 'england', 'Scotland': 'scotland', 'Wales': 'wales',
    'Northern Ireland': 'ni', 'Ireland': 'ireland', 'Isle of Man': 'iom',
    'Jersey': 'jersey', 'Guernsey': 'guernsey',
}
LON0, LAT0 = -4.0, 54.5          # projection centre
K = math.cos(math.radians(LAT0))  # equirectangular x-scale
LON_MIN, LON_MAX, LAT_MIN, LAT_MAX = -10.8, 2.0, 49.0, 61.0
SCALE = 46.0                      # px per degree of latitude
PAD = 6


def proj(lon, lat):
    x = (lon - LON_MIN) * K * SCALE + PAD
    y = (LAT_MAX - lat) * SCALE + PAD
    return x, y


def ring_path(ring):
    pts, last = [], None
    for lon, lat in ring:
        x, y = proj(lon, lat)
        p = (round(x, 1), round(y, 1))
        if p != last:
            pts.append(p)
            last = p
    if len(pts) < 3:
        return ''
    return 'M' + 'L'.join(f'{x:g},{y:g}' for x, y in pts) + 'Z'


def main(path):
    data = json.load(open(path))
    out = {}
    for f in data['features']:
        name = f['properties'].get('GEOUNIT')
        if name not in UNITS:
            continue
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        out[UNITS[name]] = ''.join(ring_path(poly[0]) for poly in polys)
    w = round((LON_MAX - LON_MIN) * K * SCALE + PAD * 2)
    h = round((LAT_MAX - LAT_MIN) * SCALE + PAD * 2)
    print('/* Generated by tools/build-map.py from Natural Earth 1:50m map units (public domain). */')
    print('window.UK_MAP = ' + json.dumps({
        'w': w, 'h': h,
        'proj': {'lonMin': LON_MIN, 'latMax': LAT_MAX, 'k': round(K, 6), 'scale': SCALE, 'pad': PAD},
        'paths': out,
    }, separators=(',', ':')) + ';')


if __name__ == '__main__':
    main(sys.argv[1])

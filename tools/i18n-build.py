"""Builds js/i18n-ru.js from the translations in i18n/ru/*.tsv (id, a tab or space, then the Russian).
Checks each translation keeps the English markup and number slots, and reports keys still missing.
Usage: python3 tools/i18n-build.py"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
keys = json.load(open(os.path.join(ROOT, 'i18n/keys.json'), encoding='utf8'))
ru, problems = {}, []
# Markup must match, apart from number slots and translatable title / aria-label / alt attributes.
tags = lambda s: sorted(re.sub(r'\{\d+\}|\{#\}', '#', re.sub(r' (title|aria-label|alt)="[^"]*"', '', t)) for t in re.findall(r'<[^>]+>', s))
for f in sorted(glob.glob(os.path.join(ROOT, 'i18n/ru/*.tsv'))):
    for n, line in enumerate(open(f, encoding='utf8'), 1):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        parts = line.split(None, 1)
        if len(parts) < 2:
            problems.append('%s:%d no text' % (os.path.basename(f), n)); continue
        i, tr = parts[0], parts[1].strip()
        en = keys.get(i)
        if en is None:
            continue  # stale: the English text has changed or gone
        if tags(en) != tags(tr):
            problems.append('%s:%d markup differs\n  EN %s\n  RU %s' % (os.path.basename(f), n, en, tr))
        slots = en.count('{#}')
        used = [int(x) for x in re.findall(r'\{(\d+)(?::[^}]*)?\}', tr)]
        if slots and (not used or max(used) >= slots):
            problems.append('%s:%d number slots: EN has %d, RU uses %s\n  EN %s\n  RU %s' % (os.path.basename(f), n, slots, used, en, tr))
        ru[i] = tr
missing = [k for k in keys if k not in ru]
with open(os.path.join(ROOT, 'js/i18n-ru.js'), 'w', encoding='utf8') as fh:
    fh.write('/* Russian translation, generated by tools/i18n-build.py from i18n/ru/*.tsv. Do not edit by hand. */\n')
    fh.write("I18N.add('ru', ")
    json.dump(ru, fh, ensure_ascii=False, separators=(',', ':'))
    fh.write(');\n')
print('%d translated, %d missing, %d problems' % (len(ru), len(missing), len(problems)))
for p in problems[:40]:
    print(p)
